
/**
 * Calculadora Basica 
 * @author Aitor
 */
public class Calculadora {

	/**
	 * Este metodo sirve para sumar dos numeros
	 * @param a primer numero de la suma
	 * @param b segundo numero de la suma
	 * @return la suma de a + b
	 */

	public static int suma(int a, int b) {

		return a + b;
	}

	/**
	 * Este metodo sirve para restar dos numeros
	 * @param a primer numero de la resta
	 * @param b segundo numero de la resta
	 * @return la resta de a - b
	 */
	public static int resta(int a, int b) {

		return a - b;
	}
}
